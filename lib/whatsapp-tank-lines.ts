export function formatTankListLinesForLang(
  tanks: Array<{ id: number; name: string; ward: string | null }>,
  lang: TankListLang,
): string {
  return tanks
    .map((row) => {
      if (lang === "en") {
        const ward = row.ward?.trim() ? ` — ${row.ward}` : "";
        return `${row.id}. ${row.name}${ward}`;
      }
      const loc = BY_ID[row.id];
      if (loc) {
        return loc[lang];
      }
      const ward = row.ward?.trim() ? ` — ${row.ward}` : "";
      return `${row.id}. ${row.name}${ward}`;
    })
    .join("\n");
}
